CREATE TABLE IF NOT EXISTS content_categories (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  category_id BIGINT UNSIGNED NOT NULL,
  movie_id BIGINT UNSIGNED NULL,
  series_id BIGINT UNSIGNED NULL,
  episode_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_content_category_movie (category_id, movie_id),
  UNIQUE KEY uq_content_category_series (category_id, series_id),
  UNIQUE KEY uq_content_category_episode (category_id, episode_id),
  INDEX idx_content_categories_movie (movie_id),
  INDEX idx_content_categories_series (series_id),
  INDEX idx_content_categories_episode (episode_id),
  CONSTRAINT fk_content_categories_category FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE,
  CONSTRAINT fk_content_categories_movie FOREIGN KEY (movie_id) REFERENCES movies(id) ON DELETE CASCADE,
  CONSTRAINT fk_content_categories_series FOREIGN KEY (series_id) REFERENCES series(id) ON DELETE CASCADE,
  CONSTRAINT fk_content_categories_episode FOREIGN KEY (episode_id) REFERENCES episodes(id) ON DELETE CASCADE
);

